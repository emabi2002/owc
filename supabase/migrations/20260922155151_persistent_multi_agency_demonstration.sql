create or replace view reporting.claim_overview as
select
  c.claim_reference,
  c.scenario_id,
  cl.full_name as claimant_name,
  e.legal_name as employer_name,
  c.incident_type,
  c.status,
  c.amount_pgk,
  c.submitted_at,
  c.updated_at
from owc_core.claims c
join owc_core.claimants cl on cl.claimant_id = c.claimant_id
join owc_core.employers e on e.employer_id = c.employer_id;

