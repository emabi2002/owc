create table if not exists owc_core.claims (
  claim_id text primary key,
  scenario_id text not null references owc_core.scenarios(scenario_id),
  claim_reference text not null unique,
  claimant_id text not null references owc_core.claimants(claimant_id),
  employer_id text not null references owc_core.employers(employer_id),
  employee_no text not null,
  medical_certificate_no text,
  account_reference text,
  incident_date date not null,
  incident_type text not null,
  incident_description text not null,
  status text not null,
