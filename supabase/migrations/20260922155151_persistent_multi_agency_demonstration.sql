create table if not exists owc_core.scenarios (
  scenario_id text primary key,
  title text not null,
  narrative text not null,
  expected_outcome text not null,
  simulation boolean not null default true check (simulation = true),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists owc_core.claimants (
  claimant_id text primary key,
  scenario_id text not null references owc_core.scenarios(scenario_id),
  nid text not null unique,
  full_name text not null,
  phone text,
  email text,
  province text,
  simulation boolean not null default true check (simulation = true),
  created_at timestamptz not null default now()
);

