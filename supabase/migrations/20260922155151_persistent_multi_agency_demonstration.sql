create or replace function public.owc_demo_lookup(p_service text, p_identifier text)
returns jsonb
language plpgsql
security invoker
set search_path = pg_catalog, public
as $$
declare
  v_service text := lower(trim(p_service));
  v_identifier text := upper(trim(p_identifier));
  v_data jsonb;
  v_operation text;
  v_status text := 'success';
  v_correlation text := 'OWC-DEMO-' || upper(substr(replace(gen_random_uuid()::text, '-', ''), 1, 16));
  v_started timestamptz := clock_timestamp();
  v_mode text;
  v_scenario text;
begin
  select mode into v_mode from integration_hub.service_state where service = v_service;
  if v_mode = 'offline' then
    raise exception 'Demonstration service % is offline', v_service using errcode = 'P0001';
  end if;

  case v_service
    when 'nid' then
      v_operation := 'verify_identity';
      select jsonb_build_object('matched', true, 'nid', nid, 'firstName', first_name, 'surname', surname,
        'dateOfBirth', date_of_birth, 'province', province, 'identityStatus', identity_status), scenario_id
      into v_data, v_scenario from nid_registry.persons where nid = v_identifier and identity_status = 'VERIFIED';
      if v_data is null then v_data := jsonb_build_object('matched', false, 'nid', v_identifier); end if;
    when 'ipa' then
      v_operation := 'verify_company';
      select jsonb_build_object('active', true, 'registrationNo', registration_no, 'legalName', legal_name,
        'tradingName', trading_name, 'industry', industry, 'registeredAddress', registered_address), scenario_id
      into v_data, v_scenario from ipa_registry.companies where registration_no = v_identifier and status = 'ACTIVE';
      if v_data is null then v_data := jsonb_build_object('active', false, 'registrationNo', v_identifier); end if;
    when 'irc' then
      v_operation := 'check_compliance';
      select jsonb_build_object('found', true, 'tin', tin, 'taxpayerName', taxpayer_name,
        'registrationNo', registration_no, 'status', status), scenario_id
      into v_data, v_scenario from irc_registry.taxpayers where tin = v_identifier;
      if v_data is null then v_data := jsonb_build_object('found', false, 'tin', v_identifier, 'status', 'UNKNOWN'); end if;
    when 'employer' then
      v_operation := 'verify_employment';
      select jsonb_build_object('employed', true, 'employeeNo', employee_no, 'nid', nid,
        'employerRegistrationNo', employer_registration_no, 'employeeName', employee_name, 'position', position,
        'workLocation', work_location, 'fortnightlySalaryPgk', fortnightly_salary_pgk,
        'employmentStatus', employment_status), scenario_id
      into v_data, v_scenario from employment_registry.employees where employee_no = v_identifier and employment_status = 'ACTIVE';
      if v_data is null then v_data := jsonb_build_object('employed', false, 'employeeNo', v_identifier); end if;
    when 'medical' then
      v_operation := 'verify_certificate';
      select jsonb_build_object('valid', true, 'certificateNo', m.certificate_no, 'patientNid', m.patient_nid,
        'provider', f.facility_name, 'practitioner', p.practitioner_name, 'injuryCategory', m.injury_category,
        'incapacityDays', m.incapacity_days, 'issuedAt', m.issued_at), m.scenario_id
      into v_data, v_scenario
      from health_registry.medical_certificates m
      join health_registry.facilities f on f.facility_id = m.facility_id
      join health_registry.practitioners p on p.practitioner_id = m.practitioner_id
      where m.certificate_no = v_identifier and m.status = 'VALID';
      if v_data is null then v_data := jsonb_build_object('valid', false, 'certificateNo', v_identifier); end if;
    when 'insurance' then
      v_operation := 'verify_policy';
      select jsonb_build_object('active', true, 'policyNo', p.policy_no,
        'employerRegistrationNo', p.employer_registration_no, 'insurer', i.insurer_name,
        'coverType', p.cover_type, 'expiryDate', p.expiry_date), p.scenario_id
      into v_data, v_scenario from insurance_registry.policies p
      join insurance_registry.insurers i on i.insurer_id = p.insurer_id
      where p.policy_no = v_identifier and p.status = 'ACTIVE';
      if v_data is null then v_data := jsonb_build_object('active', false, 'policyNo', v_identifier); end if;
    when 'bank' then
      v_operation := 'verify_account';
      select jsonb_build_object('verified', true, 'accountReference', a.account_reference,
        'bankName', b.bank_name, 'accountName', a.account_name, 'maskedAccountNumber', a.masked_account_number), a.scenario_id
      into v_data, v_scenario from banking_registry.accounts a
      join banking_registry.banks b on b.bank_id = a.bank_id
      where a.account_reference = v_identifier and a.status = 'VERIFIED';
      if v_data is null then v_data := jsonb_build_object('verified', false, 'accountReference', v_identifier); end if;
    else
      raise exception 'Unknown demonstration service: %', v_service using errcode = '22023';
  end case;

  if coalesce((v_data ->> coalesce(
    case v_service when 'nid' then 'matched' when 'ipa' then 'active' when 'irc' then 'found'
      when 'employer' then 'employed' when 'medical' then 'valid' when 'insurance' then 'active' when 'bank' then 'verified' end,
    'matched'))::boolean, false) = false then
    v_status := 'not_found';
  end if;

  insert into integration_hub.events (correlation_id, service, operation, status, duration_ms, scenario_id)
  values (v_correlation, v_service, v_operation, v_status,
    greatest(0, floor(extract(epoch from (clock_timestamp() - v_started)) * 1000)::integer), v_scenario);

  return jsonb_build_object('source', 'persistent_demo', 'service', v_service, 'operation', v_operation,
    'correlationId', v_correlation, 'timestamp', now(), 'data', v_data);
end;
$$;

create or replace function public.owc_demo_process_payment(
  p_idempotency_key text,
  p_claim_reference text,
  p_account_reference text,
  p_amount_pgk numeric
)
returns jsonb
language plpgsql
security invoker
set search_path = pg_catalog, public
as $$
declare
  v_transaction banking_registry.simulated_transactions%rowtype;
  v_account banking_registry.accounts%rowtype;
  v_bank_name text;
  v_duplicate boolean := false;
  v_sequence text;
  v_correlation text := 'OWC-DEMO-' || upper(substr(replace(gen_random_uuid()::text, '-', ''), 1, 16));
begin
  if nullif(trim(p_idempotency_key), '') is null then raise exception 'Idempotency key is required' using errcode = '22023'; end if;
  if p_amount_pgk is null or p_amount_pgk <= 0 then raise exception 'Amount must be greater than zero' using errcode = '22023'; end if;

  select * into v_transaction from banking_registry.simulated_transactions where idempotency_key = p_idempotency_key;
  if found then
    v_duplicate := true;
  else
    select * into v_account from banking_registry.accounts
    where account_reference = upper(trim(p_account_reference)) and status = 'VERIFIED';
    if not found then raise exception 'Simulated payment requires a verified demonstration bank account' using errcode = 'P0001'; end if;
    if not exists (select 1 from owc_core.claims where claim_reference = upper(trim(p_claim_reference))) then
      raise exception 'Unknown demonstration claim reference' using errcode = 'P0001';
    end if;

    v_sequence := upper(substr(replace(gen_random_uuid()::text, '-', ''), 1, 8));
    insert into banking_registry.simulated_transactions
      (idempotency_key, transaction_reference, receipt_reference, claim_reference, account_reference, amount_pgk)
    values
      (p_idempotency_key,
       'SIM-PAY-' || extract(year from now())::integer || '-' || v_sequence,
       'SIM-RCPT-' || extract(year from now())::integer || '-' || v_sequence,
       upper(trim(p_claim_reference)), v_account.account_reference, p_amount_pgk)
    on conflict (idempotency_key) do nothing
    returning * into v_transaction;
    if not found then
      select * into v_transaction from banking_registry.simulated_transactions
      where idempotency_key = p_idempotency_key;
      v_duplicate := true;
    end if;
  end if;

  select * into v_account from banking_registry.accounts
  where account_reference = v_transaction.account_reference;
  select b.bank_name into v_bank_name from banking_registry.accounts a
  join banking_registry.banks b on b.bank_id = a.bank_id
  where a.account_reference = v_transaction.account_reference;

  insert into integration_hub.events (correlation_id, service, operation, status, duration_ms)
  values (v_correlation, 'bank', 'process_payment', 'success', 0);
  insert into audit.events (action, entity_type, entity_reference, metadata)
  values ('SIMULATED_PAYMENT', 'claim', v_transaction.claim_reference,
    jsonb_build_object('transactionReference', v_transaction.transaction_reference, 'moneyMovement', false));

  return jsonb_build_object('source', 'persistent_demo', 'service', 'bank', 'operation', 'process_payment',
    'correlationId', v_correlation, 'timestamp', now(), 'data', jsonb_build_object(
      'transactionReference', v_transaction.transaction_reference, 'receiptReference', v_transaction.receipt_reference,
      'status', v_transaction.status, 'simulation', v_transaction.simulation, 'moneyMovement', v_transaction.money_movement,
      'currency', v_transaction.currency, 'generatedAt', v_transaction.generated_at,
      'claimReference', v_transaction.claim_reference, 'accountReference', v_transaction.account_reference,
      'bankName', v_bank_name, 'accountName', v_account.account_name,
      'maskedAccountNumber', v_account.masked_account_number, 'amountPgk', v_transaction.amount_pgk,
      'duplicateRequest', v_duplicate));
end;
$$;

create or replace function public.owc_demo_list_events(p_limit integer default 100)
returns jsonb
language sql
security invoker
set search_path = pg_catalog, public
as $$
  select coalesce(jsonb_agg(jsonb_build_object(
    'id', e.event_id, 'correlationId', e.correlation_id, 'service', e.service,
    'operation', e.operation, 'status', e.status, 'durationMs', e.duration_ms,
    'source', e.source, 'scenarioId', e.scenario_id, 'timestamp', e.occurred_at
  ) order by e.occurred_at desc), '[]'::jsonb)
  from (select * from integration_hub.events order by occurred_at desc limit greatest(1, least(coalesce(p_limit, 100), 500))) e;
$$;

create or replace function public.owc_demo_list_service_state()
returns jsonb
language sql
security invoker
