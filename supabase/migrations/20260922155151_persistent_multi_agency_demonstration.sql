as $$
  select coalesce(jsonb_agg(jsonb_build_object(
    'service', service, 'mode', mode, 'latencyMs', latency_ms, 'message', message, 'updatedAt', updated_at
  ) order by service), '[]'::jsonb)
  from integration_hub.service_state;
$$;

create or replace function public.owc_demo_send_notification(
  p_channel text,
  p_recipient text,
  p_event text,
  p_message text,
  p_claim_reference text default null
)
returns jsonb
language plpgsql
security invoker
set search_path = pg_catalog, public
as $$
declare
  v_delivery text := 'MSG-' || upper(substr(replace(gen_random_uuid()::text, '-', ''), 1, 16));
  v_correlation text := 'OWC-DEMO-' || upper(substr(replace(gen_random_uuid()::text, '-', ''), 1, 16));
begin
  if p_channel not in ('email', 'sms', 'in_app') then raise exception 'Unsupported notification channel' using errcode = '22023'; end if;
  insert into owc_core.communications
    (claim_reference, channel, recipient, event_name, message, delivery_reference)
  values (p_claim_reference, p_channel, p_recipient, p_event, p_message, v_delivery);
  insert into integration_hub.events (correlation_id, service, operation, status, duration_ms)
  values (v_correlation, 'notifications', 'send_notification', 'success', 0);
  return jsonb_build_object('source', 'persistent_demo', 'service', 'notifications', 'operation', 'send_notification',
    'correlationId', v_correlation, 'timestamp', now(), 'data', jsonb_build_object(
      'accepted', true, 'deliveryReference', v_delivery, 'channel', p_channel,
      'recipient', p_recipient, 'event', p_event, 'message', p_message));
end;
$$;

